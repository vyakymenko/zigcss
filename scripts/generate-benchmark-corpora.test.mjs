import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { transform } from 'lightningcss'

import {
  expectedCorpus,
  repositoryRoot,
  validateRepository,
  writeRepository,
} from './generate-benchmark-corpora.mjs'

test('corpus generation is deterministic and records exact complexity', () => {
  const first = expectedCorpus()
  const second = expectedCorpus()

  assert.deepEqual(first, second)
  assert.deepEqual(first.manifest.corpora.map(corpus => corpus.id), [
    'small-flat',
    'medium-flat',
    'large-flat',
  ])
  assert.deepEqual(first.manifest.corpora.map(corpus => corpus.complexity.qualifiedRules), [1, 128, 2048])
  assert.deepEqual(first.manifest.corpora.map(corpus => corpus.complexity.declarations), [5, 640, 10240])
  assert.ok(first.manifest.corpora[0].bytes < first.manifest.corpora[1].bytes)
  assert.ok(first.manifest.corpora[1].bytes < first.manifest.corpora[2].bytes)
  assert.ok(first.manifest.corpora.every(corpus => /^[0-9a-f]{64}$/.test(corpus.sha256)))
})

test('checked-in versioned corpus matches generated bytes and manifest', () => {
  const report = validateRepository(repositoryRoot)

  assert.equal(report.version, 'v1')
  assert.equal(report.corpora, 3)
  assert.equal(report.qualifiedRules, 2177)
  assert.equal(report.declarations, 10885)
  assert.ok(report.bytes > 100_000)
})

test('every versioned input parses with the pinned independent CSS parser', () => {
  for (const corpus of expectedCorpus().files) {
    assert.doesNotThrow(() => transform({
      code: Buffer.from(corpus.content),
      filename: corpus.name,
      errorRecovery: false,
      minify: false,
    }), corpus.name)
  }
})

test('validation fails closed on content drift, extra files, and symlinks', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'zigcss-benchmark-corpora-'))
  try {
    writeRepository(root)
    const small = path.join(root, 'benchmarks/corpora/v1/small.css')
    fs.appendFileSync(small, '\n')
    assert.throws(() => validateRepository(root), /stale corpus file: small\.css/)

    writeRepository(root)
    const manifest = path.join(root, 'benchmarks/corpora/v1/manifest.json')
    fs.appendFileSync(manifest, '\n')
    assert.throws(() => validateRepository(root), /stale corpus manifest/)

    writeRepository(root)
    fs.writeFileSync(path.join(root, 'benchmarks/corpora/v1/unowned.css'), '.extra{}\n')
    assert.throws(() => validateRepository(root), /unexpected corpus inventory/)

    fs.rmSync(path.join(root, 'benchmarks/corpora/v1/unowned.css'))
    fs.rmSync(small)
    fs.symlinkSync(path.join(root, 'benchmarks/corpora/v1/medium.css'), small)
    assert.throws(() => validateRepository(root), /corpus entry .* must be a regular non-symlink file/)

    fs.rmSync(small)
    fs.writeFileSync(small, Buffer.alloc((1024 * 1024) + 1))
    assert.throws(() => validateRepository(root), /must contain 1 through 1048576 bytes/)
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})

test('Zig benchmark embeds the closed corpus instead of generating inputs at runtime', () => {
  const build = fs.readFileSync(path.join(repositoryRoot, 'build.zig'), 'utf8')
  const source = fs.readFileSync(path.join(repositoryRoot, 'src/benchmarks.zig'), 'utf8')

  for (const size of ['small', 'medium', 'large']) {
    assert.match(build, new RegExp(`addAnonymousImport\\(\\"benchmark-${size}-css\\"`))
    assert.match(source, new RegExp(`@embedFile\\(\\"benchmark-${size}-css\\"\\)`))
  }
  assert.doesNotMatch(source, /large_css_buf|writer\.print\(\"\.class-/)
})

test('corpus check command reports exact recorded totals', () => {
  const result = spawnSync(process.execPath, ['scripts/generate-benchmark-corpora.mjs', '--check'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  })

  assert.equal(result.status, 0, result.stderr)
  assert.match(result.stdout, /v1: 3 corpora, \d+ bytes, 2177 qualified rules, 10885 declarations/)
})
